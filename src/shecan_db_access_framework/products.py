from typing import Annotated, Any, Self

from bson import BSON, ObjectId
from bson.errors import InvalidDocument
from fastapi import APIRouter, HTTPException, Query, Request, Response
from fastapi.encoders import jsonable_encoder
from pydantic import BaseModel, ConfigDict, Field, model_validator
from pymongo import ReturnDocument
from pymongo.collection import Collection
from pymongo.errors import DuplicateKeyError


router = APIRouter(prefix="/products", tags=["products"])


class ProductPayload(BaseModel):
    model_config = ConfigDict(extra="allow")

    product_name: str = Field(min_length=1)
    product_description: str = Field(min_length=1)
    primary_photo_url: str = Field(min_length=1)

    @model_validator(mode="after")
    def validate_document(self) -> Self:
        extra = self.model_extra or {}
        if "sheurl" in extra:
            raise ValueError("sheurl must be a query parameter")
        if "_id" in extra:
            raise ValueError("_id is generated by the server")
        if any(key.startswith("$") for key in extra):
            raise ValueError("Top-level field names cannot start with $")
        try:
            BSON.encode(self.model_dump())
        except (InvalidDocument, OverflowError) as exc:
            raise ValueError("Product must contain BSON-compatible JSON") from exc
        return self


def products_collection(request: Request, sheurl: str) -> Collection:
    matches = [entry for entry in request.app.state.dbs.values() if entry["sheurl"] == sheurl]
    if not matches:
        raise HTTPException(status_code=404, detail="Unknown sheurl")
    if len({entry["dbtoken"] for entry in matches}) > 1:
        raise HTTPException(status_code=409, detail="sheurl maps to multiple databases")
    return matches[0]["database"]["products"]


def product_filter(product_id: str) -> dict[str, Any]:
    if not ObjectId.is_valid(product_id):
        raise HTTPException(status_code=422, detail="Invalid product ID")
    return {"_id": ObjectId(product_id)}


def product_response(document: dict[str, Any] | None) -> dict[str, Any]:
    if document is None:
        raise HTTPException(status_code=404, detail="Product not found")
    return jsonable_encoder(document, custom_encoder={ObjectId: str})


@router.post("", status_code=201)
def create_product(
    payload: ProductPayload,
    request: Request,
    sheurl: Annotated[str, Query(min_length=1)],
) -> dict[str, Any]:
    collection = products_collection(request, sheurl)
    document = payload.model_dump()
    try:
        document["_id"] = collection.insert_one(document).inserted_id
    except DuplicateKeyError as exc:
        raise HTTPException(status_code=409, detail="Product name already exists") from exc
    return product_response(document)


@router.get("")
def list_products(
    request: Request,
    sheurl: Annotated[str, Query(min_length=1)],
    limit: Annotated[int, Query(ge=1, le=1000)] = 100,
    skip: Annotated[int, Query(ge=0)] = 0,
) -> list[dict[str, Any]]:
    collection = products_collection(request, sheurl)
    documents = collection.find({}).skip(skip).limit(limit)
    return [product_response(document) for document in documents]


@router.get("/{product_id}")
def read_product(
    product_id: str,
    sheurl: Annotated[str, Query(min_length=1)],
    request: Request,
) -> dict[str, Any]:
    collection = products_collection(request, sheurl)
    return product_response(collection.find_one(product_filter(product_id)))


@router.put("/{product_id}")
def update_product(
    product_id: str,
    payload: ProductPayload,
    request: Request,
    sheurl: Annotated[str, Query(min_length=1)],
) -> dict[str, Any]:
    collection = products_collection(request, sheurl)
    try:
        document = collection.find_one_and_replace(
            product_filter(product_id),
            payload.model_dump(),
            return_document=ReturnDocument.AFTER,
        )
    except DuplicateKeyError as exc:
        raise HTTPException(status_code=409, detail="Product name already exists") from exc
    return product_response(document)


@router.delete("", status_code=204)
def delete_product_by_name(
    request: Request,
    sheurl: Annotated[str, Query(min_length=1)],
    product_name: Annotated[str, Query(min_length=1)],
) -> Response:
    collection = products_collection(request, sheurl)
    result = collection.delete_one({"product_name": product_name})
    if result.deleted_count == 0:
        raise HTTPException(status_code=404, detail="Product not found")
    return Response(status_code=204)


@router.delete("/{product_id}", status_code=204)
def delete_product(
    product_id: str,
    sheurl: Annotated[str, Query(min_length=1)],
    request: Request,
) -> Response:
    collection = products_collection(request, sheurl)
    result = collection.delete_one(product_filter(product_id))
    if result.deleted_count == 0:
        raise HTTPException(status_code=404, detail="Product not found")
    return Response(status_code=204)
